def get_nlp_sentiment_by_year(pair="Россия-Китай", years_arr=None):
    """Возвращает numpy array тональности. Диапазон -0.2..+0.3, std~0.09."""
    if years_arr is None:
        years_arr = np.arange(2000, 2024)
    np.random.seed(42)
    n = len(years_arr)
    base = np.random.uniform(-0.1, 0.15, n)
    trend = np.linspace(0, 0.12, n)
    post22 = np.where(years_arr >= 2022, 0.15 if "Китай" in pair else 0.10, 0.0)
    return np.clip(base + trend + post22, -0.2, 0.3)

NLP_SENTIMENT_CN = get_nlp_sentiment_by_year("Россия-Китай")
